import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

// Preparation only. No database connection or upload writes.
const root = new URL('./2026-10-18/', import.meta.url);
const read = async url => JSON.parse(await readFile(url, 'utf8'));
const save = (url, value) => writeFile(url, JSON.stringify(value, null, 2) + '\n');
const hash = buffer => createHash('sha256').update(buffer).digest('hex');
const missing = await read(new URL('missing.json', root));
const manifestUrl = new URL('pack/manifest.json', root);
let manifest;
try { manifest = await read(manifestUrl); }
catch (error) {
  if (error.code !== 'ENOENT') throw error;
  manifest = { kind: 'AI_PLACEHOLDER', batch: '2026-10-18', products: [] };
}
const [slug, source] = process.argv.slice(2);
if (slug) {
  const row = missing.find(product => product.slug === slug);
  if (!row || !source) throw new Error('Expected an exact missing product slug and reviewed source file');
  if (manifest.products.some(product => product.slug === slug)) throw new Error(`Already prepared: ${slug}`);
  const original = await readFile(source);
  const buffer = await sharp(original, { failOn: 'warning', limitInputPixels: 25_000_000 })
    .rotate().resize(1024, 1024, { fit: 'inside', withoutEnlargement: true }).webp({ quality: 88 }).toBuffer();
  const dir = new URL(`pack/${row.marketPointSlug}/`, root);
  await mkdir(dir, { recursive: true });
  const file = new URL(`${slug}.webp`, dir);
  try { await writeFile(file, buffer, { flag: 'wx' }); }
  catch (error) {
    if (error.code !== 'EEXIST' || !buffer.equals(await readFile(file))) throw error;
  }
  manifest.products.push({ ...row, sha256: hash(buffer) });
  manifest.products.sort((a, b) => a.slug.localeCompare(b.slug));
  await save(manifestUrl, manifest);
}
await mkdir(new URL('pack/', root), { recursive: true });
const ready = new Set(manifest.products.map(product => product.slug));
await save(new URL('progress.json', root), { batch: manifest.batch, target: missing.length,
  prepared: ready.size, remaining: missing.filter(product => !ready.has(product.slug)).map(product => product.slug),
  products: manifest.products.map(product => ({ slug: product.slug, name: product.name,
    file: `pack/${product.marketPointSlug}/${product.slug}.webp`, sha256: product.sha256,
    source: 'BUILT_IN_IMAGEGEN', reviewed: true })),
});
// Exact immutable URLs from the existing importer are the provenance signal.
const old = await read(new URL('./2026-10-07/manifest.json', import.meta.url));
const origins = {};
for (const pack of [old, manifest]) {
  for (const product of pack.products) {
    const bytes = createHash('sha256').update(`KorzinaMarket:AI_PLACEHOLDER:${pack.batch}:${product.slug}:${product.sha256}`).digest();
    bytes[6] = (bytes[6] & 15) | 128; bytes[8] = (bytes[8] & 63) | 128;
    const hex = bytes.subarray(0, 16).toString('hex');
    origins[`/uploads/products/${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}.webp`] = product.slug;
  }
}
await writeFile(new URL('../../src/product/photo-origins.ts', import.meta.url),
  '// Generated by data/product-photos/prepare.mjs from the checked photo manifests.\n' +
  `export const photoOrigins: Readonly<Record<string, string>> = ${JSON.stringify(origins, null, 2)};\n`);
console.log(JSON.stringify({ prepared: ready.size, remaining: missing.length - ready.size, pack: fileURLToPath(new URL('pack/', root)) }));
